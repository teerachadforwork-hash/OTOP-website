def seed_default_news(db: Session):
    if db.query(models.NewsArticle).first():
        return
    admin = db.query(models.User).filter(models.User.role == models.RoleEnum.admin.value).first()
    for item in DEFAULT_NEWS:
        db.add(models.NewsArticle(author_id=admin.id if admin else None, is_published=True, **item))
    db.commit()
